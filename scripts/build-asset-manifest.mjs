// Regenerates src/cms/migration/assetManifest.ts from the files in /public.
// usage: node scripts/build-asset-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';

const MIME = { jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', svg: 'image/svg+xml', webp: 'image/webp' };
const rows = [];

const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full);
      continue;
    }
    const publicPath = `/${path.relative('public', full).split(path.sep).join('/')}`;
    const parts = publicPath.split('/');
    rows.push({
      path: publicPath,
      size: fs.statSync(full).size,
      mime: MIME[path.extname(full).slice(1).toLowerCase()] ?? 'application/octet-stream',
      category: parts[1] === 'images' ? parts[2] : 'brand',
    });
  }
};

walk('public');

const lines = rows.map(
  (r) => `  { path: '${r.path}', size: ${r.size}, mime: '${r.mime}', category: '${r.category}' },`
);
fs.writeFileSync(
  'src/cms/migration/assetManifest.ts',
  `// Inventory of the assets bundled in /public. Generated by scripts/build-asset-manifest.mjs.\n\nexport const ASSET_MANIFEST = [\n${lines.join('\n')}\n];\n`
);
console.log(`${rows.length} assets`);
