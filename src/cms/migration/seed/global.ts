const nav = (prefix: string): NavItem[] =>
  navLinks.map((link) => ({
    id: `${prefix}-${link.name.toLowerCase()}`,
    label: link.name,
    url: link.path,
    enabled: true,
  }));

const social = (platform: string, label: string, handle: string, url: string, enabled: boolean): SocialLink => ({
  id: `social-${platform}`,
  platform,
  label,
  handle,
  url,
  icon: platform,
  enabled,
});

